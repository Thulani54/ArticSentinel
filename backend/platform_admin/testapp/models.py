from django.db import models
class Company(models.Model):
    name=models.CharField(max_length=100)
    is_active=models.BooleanField(default=True)
    contact_person=models.CharField(max_length=100,blank=True)
    email=models.CharField(max_length=100,blank=True)
    phone=models.CharField(max_length=100,blank=True)
    city=models.CharField(max_length=100,blank=True)
    created_at=models.DateTimeField(auto_now_add=True)
class Device(models.Model):
    company=models.ForeignKey(Company,on_delete=models.CASCADE)
    name=models.CharField(max_length=100)
    device_id=models.CharField(max_length=100)
    device_type=models.CharField(max_length=100,default='gas_cylinder')
    location=models.CharField(max_length=100,blank=True)
    is_active=models.BooleanField(default=True)
    last_ping=models.DateTimeField(null=True)
    offline_timeout=models.PositiveIntegerField(default=10)
    created_at=models.DateTimeField(auto_now_add=True)
class Report(models.Model):
    business_id=models.IntegerField()
    report_id=models.CharField(max_length=100)
    report_name=models.CharField(max_length=100)
    report_type=models.CharField(max_length=100,default='gas')
    status=models.CharField(max_length=30,default='completed')
    generated_at=models.DateTimeField(auto_now_add=True)
    start_date=models.DateTimeField(null=True)
    end_date=models.DateTimeField(null=True)
    generated_by=models.CharField(max_length=100,blank=True)
    download_count=models.IntegerField(default=0)
    report_data=models.JSONField(default=dict)
class Alert(models.Model):
    company=models.ForeignKey(Company,on_delete=models.CASCADE)
    device=models.ForeignKey(Device,on_delete=models.CASCADE)
    title=models.CharField(max_length=100,default='Alert')
    message=models.TextField(default='')
    severity=models.CharField(max_length=20,default='critical')
    status=models.CharField(max_length=20,default='active')
    triggered_at=models.DateTimeField()
    resolved_at=models.DateTimeField(null=True)
class MaintenanceType(models.Model):
    name=models.CharField(max_length=100)
class Maintenance(models.Model):
    device=models.ForeignKey(Device,on_delete=models.CASCADE)
    maintenance_type=models.ForeignKey(MaintenanceType,on_delete=models.CASCADE)
    status=models.CharField(max_length=20,default='scheduled')
    priority=models.CharField(max_length=20,default='high')
    scheduled_date=models.DateTimeField()
    actual_end_date=models.DateTimeField(null=True)
    work_description=models.TextField(default='')
